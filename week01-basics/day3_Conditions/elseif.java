package day3_Conditions;

public class elseif {
    public static void main(String[] args) {
        int time = 20;
        if (time<12){
            System.out.println("Good Morning");
        }else if(time >21){
            System.out.println("Good Noon");
        }else{
            System.out.println("Good Evening");
        }
    }
}
